"""Verify the pinned official snapshot and regenerate the small HLS adapters."""
import argparse
import hashlib
import json
from pathlib import Path
import re
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from machsuite.cases import BENCHMARKS, SUITE

BANNER = '/* Generated by machsuite/prepare.py from the pinned official source.\n * Edit the generator, not this file. Upstream notices are retained below.\n */\n'

BFS_CHECK = r'''
int check_data(void *vdata, void *vref) {
  struct bench_args_t *data = (struct bench_args_t *)vdata;
  struct bench_args_t *ref = (struct bench_args_t *)vref;
  level_t expected[N_NODES];
  node_index_t queue[N_NODES], head = 0, tail = 0, n;
  edge_index_t counts[N_LEVELS] = {0}, e;
  if (data->starting_node >= N_NODES) return 0;
  for (n = 0; n < N_NODES; ++n) {
    expected[n] = MAX_LEVEL;
    if (data->nodes[n].edge_begin > data->nodes[n].edge_end ||
        data->nodes[n].edge_end > N_EDGES) return 0;
  }
  for (e = 0; e < N_EDGES; ++e)
    if (data->edges[e].dst >= N_NODES) return 0;
  expected[data->starting_node] = 0;
  queue[tail++] = data->starting_node;
  counts[0] = 1;
  while (head < tail) {
    n = queue[head++];
    for (e = data->nodes[n].edge_begin; e < data->nodes[n].edge_end; ++e) {
      node_index_t dst = data->edges[e].dst;
      if (expected[dst] == MAX_LEVEL) {
        if (expected[n] + 1 >= N_LEVELS || tail >= N_NODES) return 0;
        expected[dst] = expected[n] + 1;
        ++counts[(int)expected[dst]];
        queue[tail++] = dst;
      }
    }
  }
  for (n = 0; n < N_NODES; ++n)
    if (data->level[n] != expected[n]) return 0;
  for (n = 0; n < N_LEVELS; ++n)
    if (data->level_counts[n] != counts[n] || ref->level_counts[n] != counts[n]) return 0;
  return 1;
}
'''


def exact_check(field):
    return '''
int check_data(void *vdata, void *vref) {
  struct bench_args_t *data = (struct bench_args_t *)vdata;
  struct bench_args_t *ref = (struct bench_args_t *)vref;
  return memcmp(data->FIELD, ref->FIELD, sizeof(data->FIELD)) == 0;
}
'''.replace('FIELD', field)


def finite_check(spec):
    code = '''
int check_data(void *vdata, void *vref) {
  struct bench_args_t *data = (struct bench_args_t *)vdata;
  struct bench_args_t *ref = (struct bench_args_t *)vref;
'''
    for field in spec['finite_fields']:
        code += '''  for (size_t i = 0; i < sizeof(data->FIELD)/sizeof(data->FIELD[0]); ++i)
    if (!isfinite(data->FIELD[i]) || !isfinite(ref->FIELD[i])) return 0;
'''.replace('FIELD', field)
    if spec['name'] == 'md_grid':
        code += '''  for (int x = 0; x < blockSide; ++x)
    for (int y = 0; y < blockSide; ++y)
      for (int z = 0; z < blockSide; ++z)
        for (int d = 0; d < densityFactor; ++d) {
          dvector_t a = data->force[x][y][z][d], b = ref->force[x][y][z][d];
          if (!isfinite(a.x) || !isfinite(a.y) || !isfinite(a.z) ||
              !isfinite(b.x) || !isfinite(b.y) || !isfinite(b.z)) return 0;
        }
'''
    return code + '  return machsuite_upstream_check_data(vdata, vref);\n}\n'


def generate(spec, sources):
    source = sources / spec['path']
    kernel = (source / (spec['kernel'] + '.c')).read_text()
    pattern = r'^(?:void|int)\s+' + re.escape(spec['top']) + r'\s*\('
    matches = list(re.finditer(pattern, kernel, re.MULTILINE))
    if len(matches) != 1:
        raise ValueError('Expected one top definition for ' + spec['name'])
    pragmas = '#ifdef MACHSUITE_USE_AXI\n'
    for port, _, _ in spec['ports']:
        pragmas += '#pragma HLS interface port=' + port + ' mode=m_axi offset=direct\n'
    pragmas += '#endif\n'
    position = matches[0].start()
    kernel = BANNER + kernel[:position] + pragmas + kernel[position:]

    support = (source / 'local_support.c').read_text()
    anchor = '  struct bench_args_t *args = (struct bench_args_t *)vargs;\n'
    if support.count(anchor) != 1:
        raise ValueError('Unexpected run_benchmark layout for ' + spec['name'])
    allocation = '#ifdef __BAMBU_SIM__\n'
    for _, field, index in spec['ports']:
        allocation += '  m_param_alloc(%d, sizeof(args->%s));\n' % (index, field)
    allocation += '#endif\n'
    support = support.replace(anchor, anchor + allocation, 1)
    include = '#ifdef __BAMBU_SIM__\n#include <mdpi/mdpi_user.h>\n#endif\n#include <math.h>\n'
    support = BANNER + include + support
    position = support.index('int check_data(')
    if spec['name'].startswith('bfs_'):
        support = support[:position] + BFS_CHECK
    elif spec['path'].startswith('sort/'):
        support = support[:position] + exact_check('a')
    elif spec['path'].startswith('stencil/'):
        support = support[:position] + exact_check('sol')
    elif spec['finite_fields'] or spec['name'] == 'md_grid':
        support = support.replace('int check_data(', 'static int machsuite_upstream_check_data(', 1)
        support += finite_check(spec)
    return {'kernel.c': kernel, 'local_support.c': support}


def pinned_sources(directory):
    manifest = json.loads((SUITE / 'UPSTREAM.json').read_text())
    content = {}
    for relative, expected in manifest['files'].items():
        path = directory / relative
        data = path.read_bytes()
        if hashlib.sha256(data).hexdigest() != expected:
            raise ValueError('Pinned upstream hash mismatch: ' + relative)
        content[relative] = data
    return content


def prepare(check=False, import_from=None):
    sources = SUITE / 'sources'
    content = pinned_sources(import_from or sources)
    generated = {}
    for spec in BENCHMARKS:
        for filename, text in generate(spec, import_from or sources).items():
            generated[SUITE / 'adapters' / spec['path'] / filename] = text
    if check:
        different = [str(path.relative_to(SUITE)) for path, text in generated.items()
                     if not path.is_file() or path.read_bytes() != text.encode()]
        if different:
            raise ValueError('Regenerate adapters: ' + ', '.join(different))
    else:
        if import_from:
            for relative, data in content.items():
                path = sources / relative
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_bytes(data)
        for path, text in generated.items():
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    return len(content), len(generated)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Verify hashes and adapter contents without writing')
    parser.add_argument('--import-from', type=Path, help='Reimport the pinned official checkout (no download)')
    args = parser.parse_args()
    if args.check and args.import_from:
        parser.error('--check and --import-from are mutually exclusive')
    try:
        upstream, adapters = prepare(args.check, args.import_from)
        print('%s %d official files and %d adapter files.' %
              ('Verified' if args.check else 'Prepared', upstream, adapters))
    except (OSError, ValueError) as exc:
        sys.exit(str(exc))
